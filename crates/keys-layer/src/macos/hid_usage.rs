//! USB HID keyboard usage page (0x07) ↔ KeyName.

use keys_layer_core::KeyName;

pub const PAGE_KEYBOARD: u32 = 0x07;

/// Map KeyName → HID usage (keyboard page).
pub fn key_name_to_usage(name: &KeyName) -> Option<u32> {
    Some(match name.as_str() {
        "a" => 0x04,
        "b" => 0x05,
        "c" => 0x06,
        "d" => 0x07,
        "e" => 0x08,
        "f" => 0x09,
        "g" => 0x0A,
        "h" => 0x0B,
        "i" => 0x0C,
        "j" => 0x0D,
        "k" => 0x0E,
        "l" => 0x0F,
        "m" => 0x10,
        "n" => 0x11,
        "o" => 0x12,
        "p" => 0x13,
        "q" => 0x14,
        "r" => 0x15,
        "s" => 0x16,
        "t" => 0x17,
        "u" => 0x18,
        "v" => 0x19,
        "w" => 0x1A,
        "x" => 0x1B,
        "y" => 0x1C,
        "z" => 0x1D,
        "1" => 0x1E,
        "2" => 0x1F,
        "3" => 0x20,
        "4" => 0x21,
        "5" => 0x22,
        "6" => 0x23,
        "7" => 0x24,
        "8" => 0x25,
        "9" => 0x26,
        "0" => 0x27,
        "enter" | "return" => 0x28,
        "escape" => 0x29,
        "delete" | "backspace" => 0x2A,
        "tab" => 0x2B,
        "space" => 0x2C,
        "minus" | "-" => 0x2D,
        "equal" | "=" => 0x2E,
        "left_bracket" | "[" => 0x2F,
        "right_bracket" | "]" => 0x30,
        "backslash" | "\\" => 0x31,
        "semicolon" | ";" => 0x33,
        "quote" | "'" => 0x34,
        "grave" | "`" => 0x35,
        "comma" | "," => 0x36,
        "period" | "." => 0x37,
        "slash" | "/" => 0x38,
        "caps_lock" | "caps" => 0x39,
        "f1" => 0x3A,
        "f2" => 0x3B,
        "f3" => 0x3C,
        "f4" => 0x3D,
        "f5" => 0x3E,
        "f6" => 0x3F,
        "f7" => 0x40,
        "f8" => 0x41,
        "f9" => 0x42,
        "f10" => 0x43,
        "f11" => 0x44,
        "f12" => 0x45,
        "print_screen" => 0x46,
        "scroll_lock" => 0x47,
        "pause" => 0x48,
        "insert" => 0x49,
        "home" => 0x4A,
        "page_up" => 0x4B,
        "forward_delete" => 0x4C,
        "end" => 0x4D,
        "page_down" => 0x4E,
        "right" => 0x4F,
        "left" => 0x50,
        "down" => 0x51,
        "up" => 0x52,
        "left_control" => 0xE0,
        "left_shift" => 0xE1,
        "left_alt" => 0xE2,
        "left_meta" => 0xE3,
        "right_control" => 0xE4,
        "right_shift" => 0xE5,
        "right_alt" => 0xE6,
        "right_meta" => 0xE7,
        _ => return None,
    })
}

